using HRE.Definitions;

namespace HRE.Tests;

internal static class Fixtures {
    public static string MiniProject => Path.Combine(AppContext.BaseDirectory, "fixtures", "miniproj");

    /// <summary>A private copy of the mini project that a test may modify.</summary>
    public static string CopyMiniProject(string name) {
        var dir = Path.Combine(Path.GetTempPath(), "hre_project_tests", $"{name}_{Environment.ProcessId}");
        if (Directory.Exists(dir)) Directory.Delete(dir, recursive: true);
        Directory.CreateDirectory(dir);
        foreach (var file in Directory.GetFiles(MiniProject)) File.Copy(file, Path.Combine(dir, Path.GetFileName(file)));
        return dir;
    }
}

public class ProjectTests {
    [Fact]
    public void OpensTheFixture() {
        var p = Project.Open(Fixtures.MiniProject);
        Assert.Equal("miniproj", p.Manifest.Name);
        Assert.Equal(0x8000, p.Manifest.RomSize);
        Assert.Null(p.Manifest.BaseSha256);
        Assert.True(p.Flags["FEATURE_X"]);
        Assert.Equal("Feature X", p.Manifest.Features[0].Label);
        Assert.Equal(2, p.Definitions.Params.Count);
        Assert.Empty(p.Overlay.Edits);
        Assert.False(p.FlagsDirty);
        Assert.Equal(Path.Combine(Fixtures.MiniProject, "main.asm"), p.EntryPath);
        Assert.Equal(Path.Combine(Fixtures.MiniProject, "build", "miniproj.bin"), p.OutputPath);
    }

    [Fact]
    public void ConfigIncParsesAndRenders() {
        var flags = ConfigInc.Parse("; c\nFEATURE_A equ 1\nFEATURE_B EQU 0 ; off\n\n");
        Assert.True(flags["FEATURE_A"]);
        Assert.False(flags["FEATURE_B"]);
        Assert.Equal("; generated by Honda ROM Editor\nFEATURE_A EQU 1\nFEATURE_B EQU 0\n", ConfigInc.Render(flags));
    }

    /// <summary>Values are numbers in any of the assembler's forms; only zero is off.</summary>
    [Fact]
    public void ConfigIncValuesAreParsedAsNumbers() {
        var flags = ConfigInc.Parse("A EQU 00h\r\nB EQU 0x0\nC EQU 00\nD EQU 0FFh\nE EQU 0x10\nF EQU 2\nG EQU 1H\nH EQU 0X0\nI EQU yes\nJ EQU 0x\nK EQU h\n");
        var expected = new Dictionary<string, bool> {
            ["A"] = false,
            ["B"] = false,
            ["C"] = false,
            ["D"] = true,
            ["E"] = true,
            ["F"] = true,
            ["G"] = true,
            ["H"] = false,
        };
        Assert.Equal(expected, flags);
    }

    [Fact]
    public void ZeroInHexTurnsADefaultOnFeatureOff() {
        var dir = Fixtures.CopyMiniProject("hex_zero");
        File.WriteAllText(Path.Combine(dir, "config.inc"), "FEATURE_X EQU 00h\n");
        Assert.False(Project.Open(dir).Flags["FEATURE_X"]);
        File.WriteAllText(Path.Combine(dir, "config.inc"), "FEATURE_X EQU maybe\n");
        Assert.True(Project.Open(dir).Flags["FEATURE_X"]);
    }

    [Fact]
    public void FlagsAbsentFromConfigTakeTheManifestDefault() {
        var dir = Fixtures.CopyMiniProject("defaults");
        File.WriteAllText(Path.Combine(dir, "config.inc"), "");
        Assert.True(Project.Open(dir).Flags["FEATURE_X"]);
    }

    [Fact]
    public void SetFlagAndSaveRewriteOnlyConfigAndOverlay() {
        var dir = Fixtures.CopyMiniProject("save");
        var sourceBefore = File.ReadAllText(Path.Combine(dir, "main.asm"));
        var p = Project.Open(dir);
        p.SetFlag("FEATURE_X", true);
        Assert.False(p.FlagsDirty);
        p.SetFlag("FEATURE_X", false);
        Assert.True(p.FlagsDirty);
        p.Overlay = new Overlay([new OverlayEdit("tbl_fuel", 0, 99)]);
        p.Save();
        Assert.False(p.FlagsDirty);
        Assert.Equal("; generated by Honda ROM Editor\nFEATURE_X EQU 0\n", File.ReadAllText(Path.Combine(dir, "config.inc")));
        Assert.Contains("value = 99", File.ReadAllText(Path.Combine(dir, "overlay.toml")));
        Assert.Equal(sourceBefore, File.ReadAllText(Path.Combine(dir, "main.asm")));

        var reopened = Project.Open(dir);
        Assert.False(reopened.Flags["FEATURE_X"]);
        Assert.Equal([new OverlayEdit("tbl_fuel", 0, 99)], reopened.Overlay.Edits);
    }

    [Fact]
    public void MissingOverlayAndConfigReadAsEmpty() {
        var dir = Fixtures.CopyMiniProject("absent");
        File.Delete(Path.Combine(dir, "overlay.toml"));
        File.Delete(Path.Combine(dir, "config.inc"));
        var p = Project.Open(dir);
        Assert.Empty(p.Overlay.Edits);
        Assert.True(p.Flags["FEATURE_X"]);
    }

    /// <summary>
    /// Only a missing file reads as empty; one that exists but cannot be read must not be treated
    /// as empty, or the next save would overwrite it with nothing.
    /// </summary>
    [Theory]
    [InlineData("overlay.toml")]
    [InlineData("config.inc")]
    public void UnreadableOverlayOrConfigIsAnIoError(string file) {
        var dir = Fixtures.CopyMiniProject($"unreadable_{file.Replace('.', '_')}");
        File.Delete(Path.Combine(dir, file));
        Directory.CreateDirectory(Path.Combine(dir, file));
        var error = Assert.Throws<ProjectException>(() => Project.Open(dir));
        Assert.Equal(ProjectErrorKind.Io, error.Kind);
        Assert.Equal(Path.Combine(dir, file), error.Path);
    }

    /// <summary>
    /// A manifest path that leaves the project is rejected before anything is read or written
    /// through it.
    /// </summary>
    [Theory]
    [InlineData("output = \"miniproj.bin\"", "output = \"../x.bin\"", "output")]
    [InlineData("output = \"miniproj.bin\"", "output = \"sub/x.bin\"", "output")]
    [InlineData("definitions = \"definitions.toml\"", "definitions = \"C:/x.toml\"", "definitions")]
    [InlineData("definitions = \"definitions.toml\"", "definitions = \"/x.toml\"", "definitions")]
    [InlineData("entry = \"main.asm\"", "entry = \"src/../main.asm\"", "entry")]
    [InlineData("entry = \"main.asm\"", "entry = \"./main.asm\"", "entry")]
    [InlineData("config = \"config.inc\"", "config = \"\"", "config")]
    [InlineData("overlay = \"overlay.toml\"", "overlay = \"../overlay.toml\"", "overlay")]
    public void ManifestPathsMustStayInsideTheProject(string from, string to, string key) {
        var dir = Fixtures.CopyMiniProject($"paths_{Math.Abs((from + to).GetHashCode())}");
        var manifest = Path.Combine(dir, "project.toml");
        var stock = File.ReadAllText(manifest);
        Assert.Contains(from, stock);
        File.WriteAllText(manifest, stock.Replace(from, to));
        var error = Assert.Throws<ProjectException>(() => Project.Open(dir));
        Assert.Equal(ProjectErrorKind.Format, error.Kind);
        Assert.Equal(manifest, error.Path);
        Assert.Contains($"{key} = ", error.Message);
        Assert.Contains("inside the project", error.Message);
    }

    [Fact]
    public void DefinitionsMayLiveInASubdirectory() {
        var dir = Fixtures.CopyMiniProject("subdir");
        Directory.CreateDirectory(Path.Combine(dir, "defs"));
        File.Copy(Path.Combine(dir, "definitions.toml"), Path.Combine(dir, "defs", "definitions.toml"));
        var manifest = Path.Combine(dir, "project.toml");
        File.WriteAllText(manifest, File.ReadAllText(manifest).Replace("definitions = \"definitions.toml\"", "definitions = \"defs/definitions.toml\""));
        Assert.Equal(2, Project.Open(dir).Definitions.Params.Count);
    }

    [Fact]
    public void MissingManifestAndBadTomlAreErrors() {
        Assert.Equal(ProjectErrorKind.Io, Assert.Throws<ProjectException>(() => Project.Open(Path.Combine(Path.GetTempPath(), "hre_no_such_project"))).Kind);
        var dir = Fixtures.CopyMiniProject("badtoml");
        File.WriteAllText(Path.Combine(dir, "project.toml"), "name = [");
        Assert.Equal(ProjectErrorKind.Format, Assert.Throws<ProjectException>(() => Project.Open(dir)).Kind);
    }
}
