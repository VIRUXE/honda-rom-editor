using System.Globalization;
using System.Text;

namespace HRE.Definitions;

/// <summary>The feature-flag include file (<c>config.inc</c>): one <c>NAME EQU value</c> line per flag.</summary>
public static class ConfigInc {
    /// <summary>
    /// Reads <c>NAME EQU value</c> lines. The value is a number as the assembler writes it
    /// (decimal, <c>0x1F</c> or <c>1Fh</c>): zero is off and anything else on. A line whose value
    /// is not a number is ignored, so that feature keeps its manifest default.
    /// </summary>
    public static SortedDictionary<string, bool> Parse(string text) {
        var flags = new SortedDictionary<string, bool>(StringComparer.Ordinal);
        foreach (var raw in text.Split('\n')) {
            var line = raw.Split(';')[0];
            var words = line.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries);
            if (words.Length >= 3 && words[1].Equals("EQU", StringComparison.OrdinalIgnoreCase) && ParseNumber(words[2]) is { } n) {
                flags[words[0]] = n != 0;
            }
        }
        return flags;
    }

    public static string Render(IReadOnlyDictionary<string, bool> flags) {
        var sb = new StringBuilder("; generated by Honda ROM Editor\n");
        foreach (var (key, on) in flags.OrderBy(f => f.Key, StringComparer.Ordinal)) {
            sb.Append(key).Append(" EQU ").Append(on ? '1' : '0').Append('\n');
        }
        return sb.ToString();
    }

    /// <summary><c>12</c>, <c>0x0C</c> or <c>0Ch</c>.</summary>
    private static long? ParseNumber(string s) {
        if (s.StartsWith("0x", StringComparison.OrdinalIgnoreCase)) return ParseHex(s[2..]);
        if (s.EndsWith('h') || s.EndsWith('H')) return ParseHex(s[..^1]);
        return long.TryParse(s, NumberStyles.AllowLeadingSign, CultureInfo.InvariantCulture, out var n) ? n : null;
    }

    private static long? ParseHex(string digits) =>
        digits.Length > 0 && digits.All(char.IsAsciiHexDigit) && long.TryParse(digits, NumberStyles.AllowHexSpecifier, CultureInfo.InvariantCulture, out var n) ? n : null;
}
